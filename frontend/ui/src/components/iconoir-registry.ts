export type IconName = keyof typeof iconSpecs

export interface IconDefinition {
  body: string
  source: SourceName
  variant: IconVariant
}

const body = (svg: string) => {
  const start = svg.indexOf(">")
  const end = svg.lastIndexOf("</svg>")
  if (start < 0 || end < 0 || end <= start) throw new Error("Invalid bundled Iconoir SVG")
  return svg.slice(start + 1, end).trim()
}

export const iconDefinitions = Object.fromEntries(
  Object.entries(iconSpecs).map(([name, spec]) => [
    name,
    {
      body: body(sources[spec.source]),
      source: spec.source,
      variant: spec.variant,
    },
  ]),
) as Record<IconName, IconDefinition>
